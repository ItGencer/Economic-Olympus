export const translations: Record<
  Exclude<SupportedLocale, 'uk'>,
  Record<string, string>
> = {
  de,
  en,
  ja,
};

export function isSupportedLocale(value: string): value is SupportedLocale {
  return supportedLocales.includes(value as SupportedLocale);
}

export function getDictionary(locale: SupportedLocale) {
  return locale === 'uk' ? null : translations[locale];
}

export function translatePhrase(
  source: string,
  locale: SupportedLocale,
  options: { allowPartial?: boolean } = {},
) {
  if (locale === 'uk') {
    return source;
  }

  const dictionary = getDictionary(locale);

  if (!dictionary) {
    return source;
  }

  const leadingWhitespace = source.match(/^\s*/)?.[0] ?? '';
  const trailingWhitespace = source.match(/\s*$/)?.[0] ?? '';
  const normalized = source.replace(/\s+/g, ' ').trim();

  if (!normalized) {
    return source;
  }

  const exact = dictionary[normalized];

  if (exact) {
    return `${leadingWhitespace}${exact}${trailingWhitespace}`;
  }

  if (!options.allowPartial || normalized.length > 80) {
    return source;
  }

  let translated = normalized;
  const entries = Object.entries(dictionary).sort(
    ([left], [right]) => right.length - left.length,
  );

  for (const [ukPhrase, localizedPhrase] of entries) {
    if (ukPhrase.length < 3 || !translated.includes(ukPhrase)) {
      continue;
    }

    translated = translated.split(ukPhrase).join(localizedPhrase);
  }

  return translated === normalized
    ? source
    : `${leadingWhitespace}${translated}${trailingWhitespace}`;
}
